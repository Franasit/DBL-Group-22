# 5. PREPARE DAILY DATA
# ============================================================

def prepare_daily_data(df, cols):

    data = df.copy()

    # ------------------------------------------
    # Date
    # ------------------------------------------

    data[cols["date"]] = pd.to_datetime(
        data[cols["date"]],
        errors="coerce"
    )

    data = data[
        data[cols["date"]].notna()
    ].copy()

    data["year"] = data[cols["date"]].dt.year

    data = data[
        data["year"].between(
            START_YEAR,
            END_YEAR
        )
    ].copy()

    # ------------------------------------------
    # ADM2
    # ------------------------------------------

    data[cols["adm2"]] = (
        data[cols["adm2"]]
        .astype(str)
        .str.strip()
    )

    # ------------------------------------------
    # Flooded area
    # ------------------------------------------

    data[cols["flood_area"]] = pd.to_numeric(
        data[cols["flood_area"]],
        errors="coerce"
    ).fillna(0)

    data.loc[
        data[cols["flood_area"]] < 0,
        cols["flood_area"]
    ] = 0

    # ------------------------------------------
    # Flood occurrence
    # ------------------------------------------

    if cols["flood_occurrence"] is None:

        print(
            "\nNo flood-occurrence column found."
            "\nCreating flood occurrence using flooded_area_km2 > 0."
        )

        data["flood_occurrence_clean"] = (
            data[cols["flood_area"]] > 0
        ).astype(int)

    else:

        raw = data[cols["flood_occurrence"]]

        if pd.api.types.is_numeric_dtype(raw):

            data["flood_occurrence_clean"] = (
                pd.to_numeric(
                    raw,
                    errors="coerce"
                ).fillna(0) > 0
            ).astype(int)

        else:

            positive_values = {
                "true",
                "yes",
                "1",
                "flood",
                "flooded",
                "y"
            }

            data["flood_occurrence_clean"] = (
                raw
                .astype(str)
                .str.lower()
                .str.strip()
                .isin(positive_values)
            ).astype(int)

    print("\nDaily data:")
    print(f"Rows       : {len(data):,}")
    print(f"ADM2 areas : {data[cols['adm2']].nunique():,}")
    print(
        f"Period     : "
        f"{data[cols['date']].min().date()} → "
        f"{data[cols['date']].max().date()}"
    )

    return data


# ============================================================
# 6. COUNT FLOOD EVENTS
# ============================================================

def count_flood_events(group, date_col):
    """
    Count separate flood episodes.

    A new flood event begins when the time gap between
    consecutive flood days is greater than EVENT_GAP_DAYS.

    Example:

        Jan 1
        Jan 2
        Jan 3

    = one event

        Jan 1
        Jan 2
        Jan 10

    = two events
    """

    flood_dates = (
        group.loc[
            group["flood_occurrence_clean"] == 1,
            date_col
        ]
        .drop_duplicates()
        .sort_values()
    )

    if len(flood_dates) == 0:
        return 0

    gaps = flood_dates.diff().dt.days

    new_events = (
        gaps.isna()
        |
        (gaps > EVENT_GAP_DAYS)
    )

    return int(new_events.sum())



# 7. BUILD ANNUAL PROFILE
# ============================================================

def build_annual_profile(data, cols):

    group_cols = [cols["adm2"], "year"]

    if cols["adm1"]:
        group_cols.insert(0, cols["adm1"])

    annual = (
        data
        .groupby(group_cols, dropna=False)
        .agg(
            flood_days=(
                "flood_occurrence_clean",
                "sum"
            ),

            annual_mean_flooded_area_km2=(
                cols["flood_area"],
                "mean"
            ),

            annual_max_flooded_area_km2=(
                cols["flood_area"],
                "max"
            ),

            cumulative_flood_area_km2_days=(
                cols["flood_area"],
                "sum"
            )
        )
        .reset_index()
    )

    annual["flood_year"] = (
        annual["flood_days"] > 0
    ).astype(int)

    annual_file = (
        OUTPUT_DIR
        / "ADM2_annual_flood_profile.csv"
    )

    annual.to_csv(
        annual_file,
        index=False
    )

    print("\nSaved:")
    print(annual_file)

    return annual


# ============================================================
# 8. TREND CALCULATION
# ============================================================

def calculate_trend(years, values):
    """
    Linear trend:

        flood area = slope * year + intercept

    Positive slope:
        flooded area increasing

    Negative slope:
        flooded area decreasing
    """

    years = np.asarray(years, dtype=float)
    values = np.asarray(values, dtype=float)

    valid = (
        np.isfinite(years)
        &
        np.isfinite(values)
    )

    years = years[valid]
    values = values[valid]

    if len(years) < 2:
        return np.nan

    if np.all(values == values[0]):
        return 0.0

    slope = np.polyfit(
        years,
        values,
        1
    )[0]

    return float(slope)



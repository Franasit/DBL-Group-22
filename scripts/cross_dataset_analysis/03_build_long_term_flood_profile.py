def find_daily_flood_file():
    """
    Search the project for a processed ADM2 daily flood indicator file.

    Preference is given to filenames containing:
        ADM2
        flood
        daily
    """

    search_roots = [
        PROCESSED_ROOT,
        PROJECT_ROOT / "flood_processed",
        PROJECT_ROOT / "flood_data_processed",
    ]

    candidates = []

    for root in search_roots:

        if not root.exists():
            continue

        for pattern in ["*.csv", "*.parquet"]:

            for file in root.rglob(pattern):

                name = file.name.lower()

                score = 0

                if "adm2" in name:
                    score += 5

                if "flood" in name:
                    score += 5

                if "daily" in name:
                    score += 4

                if "indicator" in name:
                    score += 3

                # Avoid selecting files created by this script
                if "long_term" in name:
                    score -= 10

                if "annual" in name:
                    score -= 5

                if score > 0:
                    candidates.append((score, file))

    if not candidates:
        raise FileNotFoundError(
            "\nNo ADM2 daily flood indicator file was found.\n\n"
            "Please check that your previous script generated an ADM2 × date "
            "flood table under processed_data.\n"
        )

    candidates.sort(
        key=lambda x: (x[0], x[1].stat().st_mtime),
        reverse=True
    )

    print("\nPossible flood input files:\n")

    for score, file in candidates[:10]:
        print(f"score={score:2d} | {file}")

    selected = candidates[0][1]

    print("\nSelected input:")
    print(selected)

    return selected



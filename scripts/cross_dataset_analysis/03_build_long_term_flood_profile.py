# 11. RANKING VARIABLES
# ============================================================

def add_ranks(df):

    result = df.copy()

    result["recurrence_rank"] = (
        result["recurrence_rate"]
        .rank(
            ascending=False,
            method="min"
        )
    )

    result["severity_rank"] = (
        result["max_flood_area"]
        .rank(
            ascending=False,
            method="min"
        )
    )

    result["recent_flood_rank"] = (
        result["recent_5y_mean"]
        .rank(
            ascending=False,
            method="min"
        )
    )

    result["worsening_rank"] = (
        result["trend_slope"]
        .rank(
            ascending=False,
            method="min"
        )
    )

    return result



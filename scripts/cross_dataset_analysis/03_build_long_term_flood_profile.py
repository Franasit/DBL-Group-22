# 10. HOTSPOT CLASSIFICATION
# ============================================================

def classify_hotspots(df):
    """
    Create an exploratory flood-pattern classification.

    This is not a scientific hazard classification.
    It is an EDA tool to identify different long-term
    flood behaviours.
    """

    result = df.copy()

    # Dataset-relative thresholds
    recurrence_high = (
        result["recurrence_rate"]
        .quantile(0.67)
    )

    recurrence_low = (
        result["recurrence_rate"]
        .quantile(0.33)
    )

    max_area_high = (
        result["max_flood_area"]
        .quantile(0.75)
    )

    trend_abs = (
        result["trend_slope"]
        .abs()
    )

    meaningful_trend = (
        trend_abs.quantile(0.50)
    )

    def classify(row):

        recurrence = row["recurrence_rate"]
        trend = row["trend_slope"]
        max_area = row["max_flood_area"]

        recent = row["recent_5y_mean"]
        previous = row["previous_5y_mean"]

        # ----------------------------------
        # Emerging / worsening
        # ----------------------------------

        if (
            pd.notna(recent)
            and pd.notna(previous)
            and recent > previous
            and trend > meaningful_trend
        ):
            return "Emerging / worsening hotspot"

        # ----------------------------------
        # Declining
        # ----------------------------------

        if (
            pd.notna(recent)
            and pd.notna(previous)
            and recent < previous
            and trend < -meaningful_trend
        ):
            return "Declining flood exposure"

        # ----------------------------------
        # Chronic / recurrent
        # ----------------------------------

        if (
            recurrence >= recurrence_high
            and abs(trend) <= meaningful_trend
        ):
            return "Chronic / recurrent flooding"

        # ----------------------------------
        # Episodic extreme
        # ----------------------------------

        if (
            recurrence <= recurrence_low
            and max_area >= max_area_high
        ):
            return "Episodic extreme flood"

        return "Mixed / intermediate pattern"

    result["flood_pattern"] = result.apply(
        classify,
        axis=1
    )

    return result



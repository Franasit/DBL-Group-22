def find_column(df, possibilities, required=True):

    normalized = {
        str(col).lower().strip(): col
        for col in df.columns
    }

    # Exact matching first
    for candidate in possibilities:

        candidate_lower = candidate.lower()

        if candidate_lower in normalized:
            return normalized[candidate_lower]

    # Partial matching
    for candidate in possibilities:

        candidate_lower = candidate.lower()

        for col_lower, original in normalized.items():

            if candidate_lower in col_lower:
                return original

    if required:
        raise KeyError(
            f"\nCould not find column matching:\n"
            f"{possibilities}\n\n"
            f"Available columns:\n"
            f"{list(df.columns)}"
        )

    return None



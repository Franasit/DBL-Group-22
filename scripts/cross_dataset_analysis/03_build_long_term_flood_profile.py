# 9. LONG-TERM PROFILE
# ============================================================

def build_long_term_profile(
    daily,
    annual,
    cols
):

    results = []

    adm2_col = cols["adm2"]

    for adm2_name, annual_group in annual.groupby(adm2_col):

        annual_group = (
            annual_group
            .sort_values("year")
            .copy()
        )

        daily_group = daily[
            daily[adm2_col] == adm2_name
        ].copy()

        # --------------------------------------
        # Basic period coverage
        # --------------------------------------

        observed_years = (
            annual_group["year"]
            .nunique()
        )

        # --------------------------------------
        # Flood-year frequency
        # --------------------------------------

        flood_year_count = int(
            annual_group["flood_year"].sum()
        )

        recurrence_rate = (
            flood_year_count / observed_years
            if observed_years > 0
            else np.nan
        )

        # --------------------------------------
        # Events
        # --------------------------------------

        flood_event_count = count_flood_events(
            daily_group,
            cols["date"]
        )

        # --------------------------------------
        # Flood days
        # --------------------------------------

        flood_days = int(
            daily_group[
                "flood_occurrence_clean"
            ].sum()
        )

        # --------------------------------------
        # Area measures
        # --------------------------------------

        # Sum of annual peaks.
        #
        # More suitable than simply summing every
        # daily area value if we want a long-term
        # "flood magnitude" indicator.
        total_flooded_area_km2 = (
            annual_group[
                "annual_max_flooded_area_km2"
            ].sum()
        )

        mean_annual_flood_area = (
            annual_group[
                "annual_max_flooded_area_km2"
            ].mean()
        )

        max_flood_area = (
            annual_group[
                "annual_max_flooded_area_km2"
            ].max()
        )

        cumulative_area_days = (
            annual_group[
                "cumulative_flood_area_km2_days"
            ].sum()
        )

        # --------------------------------------
        # Recent five years
        # --------------------------------------

        recent = annual_group[
            annual_group["year"].between(
                RECENT_START,
                RECENT_END
            )
        ]

        previous = annual_group[
            annual_group["year"].between(
                PREVIOUS_START,
                PREVIOUS_END
            )
        ]

        recent_5y_mean = (
            recent[
                "annual_max_flooded_area_km2"
            ].mean()
        )

        previous_5y_mean = (
            previous[
                "annual_max_flooded_area_km2"
            ].mean()
        )

        # --------------------------------------
        # Recent change
        # --------------------------------------

        if (
            pd.notna(previous_5y_mean)
            and previous_5y_mean > 0
        ):

            recent_change_pct = (
                (
                    recent_5y_mean
                    - previous_5y_mean
                )
                / previous_5y_mean
                * 100
            )

        else:

            recent_change_pct = np.nan

        recent_absolute_change = (
            recent_5y_mean
            - previous_5y_mean
        )

        # --------------------------------------
        # Long-term trend
        # --------------------------------------

        trend_slope = calculate_trend(
            annual_group["year"],
            annual_group[
                "annual_max_flooded_area_km2"
            ]
        )

        # --------------------------------------
        # ADM1
        # --------------------------------------

        if cols["adm1"]:

            adm1_values = (
                daily_group[cols["adm1"]]
                .dropna()
                .astype(str)
            )

            adm1_name = (
                adm1_values.mode().iloc[0]
                if len(adm1_values) > 0
                else np.nan
            )

        else:
            adm1_name = np.nan

        # --------------------------------------
        # Store
        # --------------------------------------

        results.append(
            {
                "adm1_name": adm1_name,
                "adm2_name": adm2_name,

                "observed_year_count":
                    observed_years,

                "flood_year_count":
                    flood_year_count,

                "flood_event_count":
                    flood_event_count,

                "total_flooded_area_km2":
                    total_flooded_area_km2,

                "mean_annual_flood_area":
                    mean_annual_flood_area,

                "max_flood_area":
                    max_flood_area,

                "flood_days":
                    flood_days,

                "recurrence_rate":
                    recurrence_rate,

                "recent_5y_mean":
                    recent_5y_mean,

                "previous_5y_mean":
                    previous_5y_mean,

                "recent_absolute_change":
                    recent_absolute_change,

                "recent_change_pct":
                    recent_change_pct,

                "trend_slope":
                    trend_slope,

                "cumulative_flood_area_km2_days":
                    cumulative_area_days
            }
        )

    result = pd.DataFrame(results)

    return result


